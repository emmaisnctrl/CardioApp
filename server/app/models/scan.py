from app import db
from datetime import datetime

class Scan(db.Model):
    # Define the table name in the database
    __tablename__ = 'scans'

    # Primary key - unique ID for each scan, auto-increments
    id = db.Column(db.Integer, primary_key=True)

    # Foreign key - links this scan to the user who performed it
    user_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)

    # Heart rate value extracted from the PPG signal
    heart_rate = db.Column(db.Float, nullable=False)

    # Blood oxygen level extracted from the PPG signal
    spo2 = db.Column(db.Float, nullable=False)

    # Condition classification returned by the TensorFlow model
    # e.g. Normal, Tachycardia, Bradycardia, Mild Hypoxemia, Critical Hypoxemia
    condition = db.Column(db.String(100), nullable=False)

    # Confidence score of the model's classification (e.g. 0.95 = 95% confident)
    confidence_score = db.Column(db.Float, nullable=False)

    # Plain language health recommendation generated by Groq AI
    recommendation = db.Column(db.Text, nullable=False)

    # Date and time the scan was performed, set automatically
    scanned_at = db.Column(db.DateTime, default=datetime.utcnow)

    def __repr__(self):
        # This controls how a Scan object is displayed when printed
        return f'<Scan {self.id} - {self.condition}>'